// build-submittal-template.mjs — authors src/assets/submittal-cover.pdf from scratch.
//
// The app fills an AcroForm submittal cover with pdf-lib at runtime
// (src/store/submittalCover.ts). That template is a *fixture*, and a real one would be
// the contractor's own branded letterhead — so this repo generates a fictional one
// instead of shipping somebody's artwork. Run it with `npm run build:template` after
// changing any geometry here.
//
// Two contracts the runtime code depends on, so don't drift from them without updating
// submittalCover.ts in the same commit:
//
//  1. FIELD NAMES. `To name`, `To Address`, `RE:`, `Date`, `Sent Via`,
//     `SUMITTAL TITLE:` [sic — kept as-is so the field key stays stable], `Submittal
//     number`, `Other:`, `Check Box1`…`Check Box1(6)`, `Rev(1)`…`Rev(4)`, and rows 1-11
//     of `Spec / Arq Ref.(n)` / `item/Product(n)` / `QTY(n)` / `Manufacturer / Series(n)`.
//  2. GEOMETRY. Continuation sheets are built by clipping regions out of THIS page:
//     the contents band at y 428..476 and the footer below y 260.5 get re-drawn onto
//     each new sheet, and its 42 generated rows use the same column x-bounds and
//     15pt row height. See the constants block below — both files quote the same numbers.
//
// The page is legal-size media (612×1008) with a letter-size CropBox ([0,216,612,1008]).
// That is how the original scanned template was set up, and the app copies the CropBox
// onto continuation pages so they print at the same size.
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = resolve(dirname(fileURLToPath(import.meta.url)), '../src/assets/submittal-cover.pdf');

const W = 612;
const H = 1008;
const CROP_BOTTOM = 216;

const NAVY = rgb(31 / 255, 56 / 255, 100 / 255);
const BLUE = rgb(46 / 255, 116 / 255, 181 / 255);
const GRID = rgb(0.45, 0.45, 0.45);
const WHITE = rgb(1, 1, 1);
const INK = rgb(0.1, 0.1, 0.1);

// --- geometry shared with src/store/submittalCover.ts ---
const FRAME_L = 21;
const FRAME_R = 590;
const BAND_TOP = 476; // HEADER_CLIP.top
const BAND_BOTTOM = 428; // HEADER_CLIP.bottom — table rows start here, going down
const ROW_H = 15;
const ROWS = 11; // COVER_ROWS_PER_PAGE
const FOOTER_TOP = 260.5;
const COLS = [
  { name: 'Spec / Arq Ref.', header: 'Spec / Arq Ref.', x: 23, w: 79 },
  { name: 'item/Product', header: 'Item / Product', x: 102, w: 323 },
  { name: 'QTY', header: 'QTY', x: 425, w: 46 },
  { name: 'Manufacturer / Series', header: 'Manufacturer / Series', x: 471, w: 118 },
];

const COMPANY = 'KESTREL';
const COMPANY_2 = 'INTERIORS LLC';
const ADDRESS = '1400 Vessel Row, Suite 210 · Portland, OR 97209 · (503) 555-0142 · submittals@kestrel-interiors.example';

const doc = await PDFDocument.create();
const page = doc.addPage([W, H]);
page.setCropBox(0, CROP_BOTTOM, W, H - CROP_BOTTOM);
const form = doc.getForm();

const bold = await doc.embedFont(StandardFonts.HelveticaBold);
const reg = await doc.embedFont(StandardFonts.Helvetica);
const serif = await doc.embedFont(StandardFonts.TimesRomanBold);

const text = (s, x, y, size = 9, font = reg, color = INK) => page.drawText(s, { x, y, size, font, color });
const rule = (x1, y, x2, thickness = 0.8, color = GRID) =>
  page.drawLine({ start: { x: x1, y }, end: { x: x2, y }, thickness, color });
const band = (x, y, w, h, color) => page.drawRectangle({ x, y, width: w, height: h, color });

/** A labelled text field. `h` defaults to a single line. */
function field(name, x, y, w, h = 18, { multiline = false, size = 9 } = {}) {
  const f = form.createTextField(name);
  f.acroField.setDefaultAppearance(`/Helv ${size} Tf 0 g`);
  if (multiline) f.enableMultiline();
  f.addToPage(page, { x, y, width: w, height: h, borderWidth: 0.6, borderColor: GRID, backgroundColor: rgb(0.98, 0.98, 0.99) });
  return f;
}
function checkbox(name, x, y, size = 11) {
  const c = form.createCheckBox(name);
  c.addToPage(page, { x, y, width: size, height: size, borderWidth: 0.8, borderColor: NAVY });
  return c;
}
const caption = (s, x, y) => text(s, x, y, 6.5, bold, rgb(0.35, 0.35, 0.4));

/* ---------------------------------------------------------------- letterhead */
// The wordmark is drawn rather than embedded so the template stays a few KB and has no
// raster asset to license. It mirrors src/assets/demo-contractor-logo.svg.
page.drawRectangle({ x: 24, y: 946, width: 4.5, height: 34, color: NAVY });
text(COMPANY, 36, 962, 22, serif, NAVY);
text(COMPANY_2, 37, 949, 9.5, reg, BLUE);
rule(36, 944, 200, 1.2, BLUE);
text(ADDRESS, 24, 932, 7, reg, rgb(0.4, 0.4, 0.45));

band(FRAME_L, 892, FRAME_R - FRAME_L, 26, NAVY);
text('SUBMITTAL TRANSMITTAL', 30, 900, 13, bold, WHITE);
text('Generated by Material Tracker', FRAME_R - 150, 901, 8, reg, rgb(0.8, 0.85, 0.95));

/* ------------------------------------------------------------------- to / meta */
caption('TO', 27, 874);
field('To name', 27, 852, 300);
caption('ADDRESS', 27, 842);
field('To Address', 27, 802, 300, 36, { multiline: true });

caption('DATE', 360, 874);
field('Date', 360, 852, 100);
caption('SUBMITTAL NO.', 475, 874);
field('Submittal number', 475, 852, 110);
caption('SENT VIA', 360, 842);
field('Sent Via', 360, 820, 225);

caption('RE: (PROJECT)', 27, 782);
field('RE:', 27, 760, 558);

caption('SUBMITTAL TITLE', 27, 750);
field('SUMITTAL TITLE:', 27, 728, 558);

/* --------------------------------------------------------------- submittal type */
band(FRAME_L, 694, FRAME_R - FRAME_L, 18, BLUE);
text('SUBMITTAL TYPE', 30, 699, 9, bold, WHITE);

const TYPES = [
  ['Check Box1', 'Rev(1)', 'Product Data'],
  ['Check Box1(1)', 'Rev(2)', 'Shop Drawings'],
  ['Check Box1(2)', 'Rev(3)', 'Samples'],
  ['Check Box1(3)', 'Rev(4)', 'Other:'],
];
TYPES.forEach(([box, rev, label], i) => {
  const y = 670 - i * 22;
  checkbox(box, 30, y);
  text(label, 50, y + 2, 9, reg);
  if (label === 'Other:') field('Other:', 90, y - 2, 170, 16, { size: 8.5 });
  text('Rev.', 300, y + 2, 9, reg);
  field(rev, 330, y - 2, 60, 16, { size: 8.5 });
});

/* ------------------------------------------------ deviations / certification
 * These belong to the reviewer, not to us — the app never checks them, it just has to
 * leave them on the sheet so the reviewer can. */
band(FRAME_L, 566, FRAME_R - FRAME_L, 18, BLUE);
text('CONTRACTOR CERTIFICATION', 30, 571, 9, bold, WHITE);
[
  ['Check Box1(4)', 'No deviations from the contract documents.'],
  ['Check Box1(5)', 'Deviations are noted on the attached submittal data.'],
  ['Check Box1(6)', 'Field dimensions and adjacent conditions have been verified.'],
].forEach(([box, label], i) => {
  const y = 542 - i * 20;
  checkbox(box, 30, y);
  text(label, 50, y + 2, 9, reg);
});

/* ------------------------------------------------------------ submittal contents
 * y 428..476 is clipped verbatim onto every continuation sheet — anything drawn here
 * has to make sense on a page that is nothing but this band plus 42 rows. */
band(FRAME_L, 452, FRAME_R - FRAME_L, BAND_TOP - 452, NAVY);
text('SUBMITTAL CONTENTS', 30, 459, 11, bold, WHITE);
band(FRAME_L, BAND_BOTTOM, FRAME_R - FRAME_L, 452 - BAND_BOTTOM, rgb(0.88, 0.91, 0.96));
COLS.forEach((c) => {
  text(c.header, c.x + 3, BAND_BOTTOM + 8, 8, bold, NAVY);
  page.drawLine({ start: { x: c.x, y: BAND_BOTTOM }, end: { x: c.x, y: 452 }, thickness: 0.8, color: NAVY });
});

for (let r = 1; r <= ROWS; r++) {
  const y = BAND_BOTTOM - ROW_H * r;
  COLS.forEach((c) => {
    const f = form.createTextField(`${c.name}(${r})`);
    f.acroField.setDefaultAppearance('/Helv 9 Tf 0 g');
    f.addToPage(page, { x: c.x, y, width: c.w, height: ROW_H, borderWidth: 0.6, borderColor: GRID });
  });
}
// Outer frame around the contents block, matching what continuation sheets draw.
page.drawRectangle({
  x: FRAME_L, y: BAND_BOTTOM - ROW_H * ROWS, width: FRAME_R - FRAME_L,
  height: BAND_TOP - (BAND_BOTTOM - ROW_H * ROWS), borderColor: NAVY, borderWidth: 1.6,
});

/* ---------------------------------------------------------------------- footer */
rule(FRAME_L, FOOTER_TOP - 6, FRAME_R, 1.2, NAVY);
text(`${COMPANY} ${COMPANY_2}`, FRAME_L + 3, FOOTER_TOP - 20, 8, bold, NAVY);
text(ADDRESS, FRAME_L + 3, FOOTER_TOP - 31, 6.5, reg, rgb(0.45, 0.45, 0.5));
text('Fictional company — sample document generated by a portfolio demo.', FRAME_L + 3, FOOTER_TOP - 41, 6.5, reg, rgb(0.55, 0.55, 0.6));

form.updateFieldAppearances();
mkdirSync(dirname(OUT), { recursive: true });
const bytes = await doc.save();
writeFileSync(OUT, bytes);
console.log(`wrote ${OUT} — ${(bytes.length / 1024).toFixed(1)} kB, ${form.getFields().length} form fields`);
